const optionalNumber = (raw: string): number | undefined => (raw.trim() === "" || Number.isNaN(Number(raw)) ? undefined : Number(raw));

// SCR-40 "Fields": the guided builder. A field is a row; the order is the order of the form. "Different in each language" puts the field
// in `localized_schema` (one value per language), otherwise it is shared by every language (`json_schema`). The two documents are
// generated by `generateSchemas`; nothing here writes JSON by hand.
export function FieldBuilder({
  fields,
  onChange,
  disabled,
  serverFields,
}: {
  fields: BuilderField[];
  onChange: (next: BuilderField[]) => void;
  disabled: boolean;
  // Names the last 422 pointed at (rows are marked).
  serverFields: Set<string>;
}) {
  const t = useTranslations("collections.builder");
  const problems = useMemo(() => fieldProblems(fields), [fields]);
  const update = (id: string, patch: Partial<BuilderField>) => onChange(fields.map((f) => (f.id === id ? { ...f, ...patch } : f)));
  const move = (index: number, by: -1 | 1) => {
    const next = fields.slice();
    const [item] = next.splice(index, 1);
    next.splice(index + by, 0, item);
    onChange(next);
  };

  return (
    <div className="space-y-4" data-testid="field-builder">
      {fields.length === 0 ? <p className="rounded-md border border-dashed p-6 text-center text-sm leading-snug text-muted-foreground">{t("empty")}</p> : null}
      <ol className="space-y-3">
        {fields.map((field, index) => (
          <FieldRow
            key={field.id}
            field={field}
            index={index}
            count={fields.length}
            disabled={disabled}
            problems={(problems[field.id] ?? []).map((p) => t(`problems.${p.code}`, (p.params ?? {}) as Record<string, number>))}
            marked={serverFields.has(field.name)}
            onPatch={(patch) => update(field.id, patch)}
            onKind={(kind) => onChange(fields.map((f) => (f.id === field.id ? withFieldKind(f, kind) : f)))}
            onMove={(by) => move(index, by)}
            onRemove={() => onChange(fields.filter((f) => f.id !== field.id))}
          />
        ))}
      </ol>
      {!disabled ? (
        <Button type="button" variant="outline" onClick={() => onChange([...fields, newField({ name: nextName(fields) })])}>
          <PlusIcon />
          {t("add")}
        </Button>
      ) : null}
    </div>
  );
}

function nextName(fields: BuilderField[]): string {
  for (let i = fields.length + 1; i < 100; i++) {
    const name = `field_${i}`;
    if (!fields.some((f) => f.name === name)) return name;
  }
  return "";
}

function FieldRow({
  field,
  index,
  count,
  disabled,
  problems,
  marked,
  onPatch,
  onKind,
  onMove,
  onRemove,
}: {
  field: BuilderField;
  index: number;
  count: number;
  disabled: boolean;
  problems: string[];
  marked: boolean;
  onPatch: (patch: Partial<BuilderField>) => void;
  onKind: (kind: FieldKind) => void;
  onMove: (by: -1 | 1) => void;
  onRemove: () => void;
}) {
  const t = useTranslations("collections.builder");
  const ids = { name: useId(), label: useId(), kind: useId(), required: useId(), localized: useId(), desc: useId() };
  const invalid = problems.length > 0 || marked;
  return (
    <li className={cn("space-y-3 rounded-lg border bg-card p-4", invalid && "border-destructive")} data-testid="builder-field" data-field-name={field.name}>
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center gap-2">
          <span className="text-sm font-medium tabular-nums text-muted-foreground">{index + 1}</span>
          <Badge variant={field.localized ? "default" : "secondary"}>{field.localized ? t("perLanguage") : t("shared")}</Badge>
        </div>
        {!disabled ? (
          <div className="flex items-center gap-1">
            <Button type="button" variant="ghost" size="icon" className="size-8" disabled={index === 0} aria-label={t("moveUp", { name: field.name })} onClick={() => onMove(-1)}>
              <ArrowUpIcon />
            </Button>
            <Button type="button" variant="ghost" size="icon" className="size-8" disabled={index === count - 1} aria-label={t("moveDown", { name: field.name })} onClick={() => onMove(1)}>
              <ArrowDownIcon />
            </Button>
            <Button type="button" variant="ghost" size="icon" className="size-8 text-destructive" aria-label={t("remove", { name: field.name })} onClick={onRemove}>
              <Trash2Icon />
            </Button>
          </div>
        ) : null}
      </div>

      <div className="grid gap-3 md:grid-cols-3">
        <div className="space-y-1.5">
          <Label htmlFor={ids.name}>{t("name")}</Label>
          <Input id={ids.name} className="font-mono" spellCheck={false} autoComplete="off" value={field.name} disabled={disabled} aria-invalid={invalid || undefined} onChange={(e) => onPatch({ name: e.target.value })} />
        </div>
        <div className="space-y-1.5">
          <Label htmlFor={ids.label}>{t("label")}</Label>
          <Input id={ids.label} autoComplete="off" value={field.label} disabled={disabled} onChange={(e) => onPatch({ label: e.target.value })} />
        </div>
        <div className="space-y-1.5">
          <Label htmlFor={ids.kind}>{t("kind")}</Label>
          <Select value={field.fieldKind} disabled={disabled} onValueChange={(value) => onKind(value as FieldKind)}>
            <SelectTrigger id={ids.kind} className="w-full" aria-label={t("kind")}>
              <SelectValue />
            </SelectTrigger>
            <SelectContent>
              {FIELD_KINDS.map((k) => (
                <SelectItem key={k} value={k}>
                  {t(`kinds.${k}`)}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>
      </div>

      <div className="flex flex-wrap items-center gap-x-6 gap-y-2">
        <div className="flex items-center gap-2">
          <Switch id={ids.required} checked={field.required} disabled={disabled} onCheckedChange={(v) => onPatch({ required: v })} />
          <Label htmlFor={ids.required} className="font-normal">
            {t("required")}
          </Label>
        </div>
        <div className="flex items-center gap-2">
          <Switch id={ids.localized} checked={field.localized} disabled={disabled} onCheckedChange={(v) => onPatch({ localized: v })} />
          <Label htmlFor={ids.localized} className="font-normal">
            {t("localized")}
          </Label>
        </div>
      </div>

      {field.fieldKind === "array" ? (
        <ArrayOptions field={field} disabled={disabled} onPatch={onPatch} />
      ) : field.fieldKind === "richtext" ? null : (
        <SpecOptions spec={field} disabled={disabled} idPrefix={field.id} onPatch={(patch) => onPatch(patch as Partial<BuilderField>)} withPattern />
      )}

      <div className="space-y-1.5">
        <Label htmlFor={ids.desc}>{t("description")}</Label>
        <Input id={ids.desc} autoComplete="off" value={field.description} disabled={disabled} onChange={(e) => onPatch({ description: e.target.value })} />
      </div>

      {problems.length > 0 ? (
        <ul role="alert" className="list-disc space-y-0.5 pl-5 text-sm leading-snug text-destructive">
          {problems.map((p) => (
            <li key={p}>{p}</li>
          ))}
        </ul>
      ) : null}
    </li>
  );
}

// The limits of one kind of value (a field, or the item of an array).
function SpecOptions({
  spec,
  disabled,
  idPrefix,
  onPatch,
  withPattern,
}: {
  spec: ScalarSpec;
  disabled: boolean;
  idPrefix: string;
  onPatch: (patch: Partial<ScalarSpec>) => void;
  withPattern: boolean;
}) {
  const t = useTranslations("collections.builder");
  const id = (s: string) => `${idPrefix}-${s}`;
  if (spec.kind === "string" || spec.kind === "text") {
    return (
      <div className="grid gap-3 md:grid-cols-3">
        <div className="space-y-1.5">
          <Label htmlFor={id("minLength")}>{t("minLength")}</Label>
          <Input id={id("minLength")} type="number" min={0} value={spec.minLength ?? ""} disabled={disabled} onChange={(e) => onPatch({ minLength: optionalNumber(e.target.value) })} />
        </div>
        <div className="space-y-1.5">
          <Label htmlFor={id("maxLength")}>{t("maxLength")}</Label>
          <Input id={id("maxLength")} type="number" min={1} value={spec.maxLength ?? ""} disabled={disabled} onChange={(e) => onPatch({ maxLength: optionalNumber(e.target.value) })} />
        </div>
        {withPattern && spec.kind === "string" ? (
          <div className="space-y-1.5">
            <Label htmlFor={id("pattern")}>{t("pattern")}</Label>
            <Input id={id("pattern")} className="font-mono" spellCheck={false} value={spec.pattern ?? ""} disabled={disabled} onChange={(e) => onPatch({ pattern: e.target.value === "" ? undefined : e.target.value })} />
          </div>
        ) : null}
      </div>
    );
  }
  if (spec.kind === "number" || spec.kind === "integer") {
    return (
      <div className="grid gap-3 md:grid-cols-3">
        <div className="space-y-1.5">
          <Label htmlFor={id("minimum")}>{t("minimum")}</Label>
          <Input id={id("minimum")} type="number" value={spec.minimum ?? ""} disabled={disabled} onChange={(e) => onPatch({ minimum: optionalNumber(e.target.value) })} />
        </div>
        <div className="space-y-1.5">
          <Label htmlFor={id("maximum")}>{t("maximum")}</Label>
          <Input id={id("maximum")} type="number" value={spec.maximum ?? ""} disabled={disabled} onChange={(e) => onPatch({ maximum: optionalNumber(e.target.value) })} />
        </div>
      </div>
    );
  }
  if (spec.kind === "enum") {
    return (
      <div className="space-y-1.5">
        <Label htmlFor={id("options")}>{t("options")}</Label>
        <Textarea
          id={id("options")}
          rows={3}
          className="font-mono leading-snug"
          value={spec.options.join("\n")}
          disabled={disabled}
          onChange={(e) => onPatch({ options: e.target.value.split("\n") })}
        />
        <p className="text-xs leading-snug text-muted-foreground">{t("optionsHint")}</p>
      </div>
    );
  }
  return null;
}

function ArrayOptions({ field, disabled, onPatch }: { field: BuilderField; disabled: boolean; onPatch: (patch: Partial<BuilderField>) => void }) {
  const t = useTranslations("collections.builder");
  const id = (s: string) => `${field.id}-${s}`;
  return (
    <div className="space-y-3 rounded-md bg-muted/50 p-3">
      <div className="grid gap-3 md:grid-cols-4">
        <div className="space-y-1.5">
          <Label htmlFor={id("item-kind")}>{t("itemKind")}</Label>
          <Select value={field.item.kind} disabled={disabled} onValueChange={(v) => onPatch({ item: { kind: v as ScalarKind, options: [] } })}>
            <SelectTrigger id={id("item-kind")} className="w-full" aria-label={t("itemKind")}>
              <SelectValue />
            </SelectTrigger>
            <SelectContent>
              {ITEM_KINDS.map((k) => (
                <SelectItem key={k} value={k}>
                  {t(`kinds.${k}`)}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>
        <div className="space-y-1.5">
          <Label htmlFor={id("minItems")}>{t("minItems")}</Label>
          <Input id={id("minItems")} type="number" min={0} value={field.minItems ?? ""} disabled={disabled} onChange={(e) => onPatch({ minItems: optionalNumber(e.target.value) })} />
        </div>
        <div className="space-y-1.5">
          <Label htmlFor={id("maxItems")}>{t("maxItems", { max: MAX_ARRAY_ITEMS })}</Label>
          <Input id={id("maxItems")} type="number" min={1} max={MAX_ARRAY_ITEMS} value={field.maxItems} disabled={disabled} onChange={(e) => onPatch({ maxItems: Number(e.target.value) || 0 })} />
        </div>
        <div className="flex items-end gap-2 pb-2">
          <Switch id={id("unique")} checked={field.uniqueItems} disabled={disabled} onCheckedChange={(v) => onPatch({ uniqueItems: v })} />
          <Label htmlFor={id("unique")} className="font-normal">
            {t("unique")}
          </Label>
        </div>
      </div>
      <SpecOptions spec={field.item} disabled={disabled} idPrefix={`${field.id}-item`} withPattern onPatch={(patch) => onPatch({ item: { ...field.item, ...patch } })} />
    </div>
  );
}
